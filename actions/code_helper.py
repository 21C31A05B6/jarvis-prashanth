def _run_action(file_path: str, description: str, args: list, timeout: int, player) -> ToolResult:
    # 1. If explicit file path provided
    if file_path:
        p = Path(file_path)
        if not p.is_absolute():
            if (BASE_DIR / p).exists():
                p = BASE_DIR / p
            elif (DESKTOP / p).exists():
                p = DESKTOP / p
        if p.is_file():
            if player:
                player.write_log(f"[Code] Running {p.name}...")
            return _run_file(p, args, timeout)
        elif p.is_dir():
            for candidate in ("run_jarvis.bat", "run.bat", "start.bat", "main.py", "app.py", "index.js"):
                target = p / candidate
                if target.is_file():
                    if player:
                        player.write_log(f"[Code] Running {target.name} in {p.name}...")
                    return _run_file(target, args, timeout)

    # 2. If description indicates running the project or a shell command
    desc = (description or "").strip()
    if desc:
        desc_lower = desc.lower()
        project_launch_keywords = (
            "run project", "start project", "launch project",
            "run the project", "start the project",
            "start jarvis", "run jarvis", "launch jarvis",
            "run app", "start app", "launch app"
        )
        # Only treat as project launch if it's explicitly a short natural language request
        if desc_lower in project_launch_keywords or (
            any(desc_lower.startswith(kw) for kw in project_launch_keywords)
            and not any(ch in desc for ch in ("-", "/", "\\", '"', "'", ";", "|", "&", ">", "<", "$"))
        ):
            for candidate in ("run_jarvis.bat", "run.bat", "main.py", "app.py"):
                target = BASE_DIR / candidate
                if target.is_file():
                    if player:
                        player.write_log(f"[Code] Running project entrypoint ({target.name})...")
                    return _run_file(target, args, timeout)
        if player:
            player.write_log(f"[Code] Executing command: {desc}...")
        return _run_shell_command(desc, timeout)

    # 3. Fallback: discover project entrypoint in workspace
    for candidate in ("run_jarvis.bat", "run.bat", "main.py", "app.py"):
        target = BASE_DIR / candidate
        if target.is_file():
            if player:
                player.write_log(f"[Code] Running project entrypoint ({target.name})...")
            return _run_file(target, args, timeout)

    return ToolResult.fail("No executable file or project found to run.", ErrorCategory.FILE_NOT_FOUND)


def _optimize_action(file_path, code, language, output_path, player) -> ToolResult:
    if file_path and not code:
        code, err = _read_file(file_path)
        if err:
            return ToolResult.fail(err, ErrorCategory.FILE_NOT_FOUND)
    if not code:
        return ToolResult.fail("Please provide code or a file path to optimize, sir.", ErrorCategory.COMMAND_UNDERSTOOD_TOOL_UNAVAILABLE)

    if player:
        player.write_log("[Code] Optimizing code...")

    lang  = language or "python"
    model = _get_gemini()

    prompt = f"""You are an expert {lang} developer and code reviewer.
Optimize the following code for:
1. Performance — eliminate unnecessary operations, use efficient data structures
2. Readability — clear variable names, proper formatting, logical structure
3. Best practices — modern {lang} patterns, error handling, type hints if applicable
4. Remove dead code, redundant comments, and unnecessary complexity

Return ONLY the optimized code — no explanation, no markdown, no backticks.

Original code:
{code[:6000]}

Optimized code:"""

    try:
        response  = model.generate_content(prompt)
        optimized = _clean_code(response.text)
    except Exception as e:
        cat = classify_error(e)
        return ToolResult.fail(f"Could not optimize code: {e}", cat)

    if file_path:
        save_path = Path(file_path)
    else:
        save_path = _resolve_save_path(output_path, lang)

    status = _save_file(save_path, optimized)
    print(f"[Code] ✅ Optimized: {save_path}")

    original_lines  = len(code.splitlines())
    optimized_lines = len(optimized.splitlines())
    diff = original_lines - optimized_lines

    msg = (
        f"Code optimized. {status}\n"
        f"Lines: {original_lines} → {optimized_lines} "
        f"({'−' if diff > 0 else '+'}{abs(diff)} lines)\n\n"
        f"Preview:\n{_preview(optimized)}"
    )
    return ToolResult.ok(
        msg,
        data={"path": str(save_path), "diff": diff},
        artifacts=[str(save_path)],
        verification={"exists": save_path.exists(), "size": save_path.stat().st_size},
    )


def _screen_debug_action(description, file_path, player, speak=None) -> ToolResult:
    if player:
        player.write_log("[Code] Taking screenshot for analysis...")

    print("[Code] 📸 Capturing screen for debug...")

    screenshot_path = _take_screenshot()
    if not screenshot_path:
        return ToolResult.fail("Could not take screenshot, sir. Please make sure PyAutoGUI is installed.", ErrorCategory.TOOL_EXECUTION_FAILED)

    file_content = ""
    if file_path:
        file_content, err = _read_file(file_path)
        if err:
            print(f"[Code] ⚠️ Could not read file: {err}")

    try:
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=_get_api_key())

        image_bytes  = screenshot_path.read_bytes()
        user_question = description or "What error or problem do you see on the screen? How can it be fixed?"

        context = ""
        if file_content:
            context = f"\n\nAdditionally, here is the related file content:\n```\n{file_content[:4000]}\n```"

        analysis_prompt = f"""You are an expert programmer and debugger analyzing a screenshot.

User's question: {user_question}{context}

Please:
1. Identify any errors, exceptions, or problems visible on the screen
2. Explain what is causing the problem in simple terms
3. Provide a concrete fix or solution
4. If there's code visible, show the corrected version

Be specific and actionable. If you see an error message, quote it exactly."""

        contents = [
            types.Part.from_bytes(data=image_bytes, mime_type="image/png"),
            analysis_prompt,
        ]

        response = client.models.generate_content(
            model="gemini-3.6-flash",
            contents=contents,
        )

        analysis = response.text.strip()
        print(f"[Code] ✅ Screen analysis complete")

        try:
            screenshot_path.unlink()
        except Exception:
            pass

        saved_artifacts = []
        if file_path and file_content:
            code_match = re.search(r"```[a-zA-Z]*\n(.*?)```", analysis, re.DOTALL)
            if code_match:
                fixed_code = code_match.group(1).strip()
                save_path  = Path(file_path)
                _save_file(save_path, fixed_code)
                analysis += f"\n\n✅ Fixed code has been saved to: {file_path}"
                saved_artifacts.append(file_path)
                print(f"[Code] ✅ Fixed code saved: {file_path}")

        return ToolResult.ok(analysis, artifacts=saved_artifacts)

    except Exception as e:
        try:
            screenshot_path.unlink()
        except Exception:
            pass
        cat = classify_error(e)
        return ToolResult.fail(f"Screen analysis failed: {e}", cat)


def code_helper(
    parameters: dict,
    response=None,
    player=None,
    session_memory=None,
    speak=None
) -> ToolResult:
    """
    Called from main.py.

    parameters:
        action      : write | edit | explain | run | build | screen_debug | optimize | auto
        description : What the code should do / what change to make / what problem to analyze
        language    : Programming language (default: python)
        output_path : Where to save — user specifies full path or filename
        file_path   : Path to existing file (edit / explain / run / build / optimize)
        code        : Raw code string (explain/optimize without a file)
        args        : CLI argument list for run/build
        timeout     : Execution timeout in seconds (default: 30)
    """
    p           = parameters or {}
    action      = p.get("action", "auto").lower().strip()
    description = p.get("description", "").strip()
    language    = p.get("language", "python").strip()
    output_path = p.get("output_path", "").strip()
    file_path   = p.get("file_path", "").strip()
    code        = p.get("code", "").strip()
    args        = p.get("args", [])
    timeout     = int(p.get("timeout", 30))

    if action == "auto":
        action = _detect_intent(description, file_path, code)
        print(f"[Code] 🤖 Auto-detected: {action}")

    if action == "write":
        result = _write_action(description, language, output_path, player)
    elif action == "edit":
        result = _edit_action(file_path, description or p.get("instruction", ""), player)
    elif action == "explain":
        result = _explain_action(file_path, code, player)
    elif action in ("run", "command", "terminal", "exec", "execute"):
        result = _run_action(file_path, description, args, timeout, player)
    elif action == "build":
        result = _build(description, language, output_path, args, timeout, speak, player)
    elif action == "optimize":
        result = _optimize_action(file_path, code, language, output_path, player)
    elif action == "screen_debug":
        result = _screen_debug_action(description, file_path, player, speak)
    else:
        result = ToolResult.fail(
            f"Unknown action: '{action}'. Use write, edit, explain, run, build, optimize, or screen_debug.",
            ErrorCategory.COMMAND_UNDERSTOOD_TOOL_UNAVAILABLE,
        )

    return coerce_tool_result(result)
