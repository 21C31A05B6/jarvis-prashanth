def _detect_intent(description: str, file_path: str, code: str) -> str:
    desc = (description or "").lower()

    screen_kw = ["ekrandaki", "screen", "ekranda", "bu hatayı", "why am i getting",
                 "neden hata", "what's wrong", "ne yanlış", "screenshot", "görüntü"]
    if any(k in desc for k in screen_kw):
        return "screen_debug"

    optimize_kw = ["optimize", "refactor", "clean up", "improve", "temizle",
                   "iyileştir", "daha iyi", "make it better", "hızlandır"]
    if any(k in desc for k in optimize_kw) and (code or file_path):
        return "optimize"

    if file_path:
        p = Path(file_path)
        edit_kw  = ["edit", "update", "modify", "change", "add", "remove",
                    "refactor", "fix", "rename", "replace", "düzenle", "değiştir"]
        run_kw   = ["run", "execute", "launch", "start", "çalıştır"]
        build_kw = ["build", "make it work", "try", "attempt"]

        if p.exists() and any(k in desc for k in edit_kw):
            return "edit"
        if p.exists() and any(k in desc for k in run_kw):
            return "run"
        if any(k in desc for k in build_kw):
            return "build"
        if p.exists():
            return "explain"

    explain_kw = ["explain", "what does", "describe", "analyze", "açıkla", "ne yapıyor"]
    if any(k in desc for k in explain_kw) and (code or file_path):
        return "explain"

    build_kw = ["build", "make it work", "try and", "attempt"]
    if any(k in desc for k in build_kw):
        return "build"

    return "write"

def _write(description: str, language: str, output_path: str, player=None) -> tuple[str, Path]:
    lang  = language or "python"
    model = _get_gemini()

    prompt = f"""You are an expert {lang} developer.
Write clean, working, well-commented {lang} code for the description below.

Rules:
- Output ONLY the code. No explanation, no markdown, no backticks.
- Add helpful inline comments.
- Handle errors and edge cases properly.
- Use modern best practices.

Description: {description}

Code:"""

    response = model.generate_content(prompt)
    code     = _clean_code(response.text)
    path     = _resolve_save_path(output_path, lang)
    _save_file(path, code, f"Generated {lang} code for request: {description}")
    return code, path


def _fix_code(code: str, error_output: str, description: str) -> str:
    model  = _get_gemini()
    prompt = f"""You are an expert debugger.
The code below failed with the following error. Fix it.
Return ONLY the corrected code — no explanation, no markdown, no backticks.

Original goal: {description}

Error:
{error_output[:2000]}

Broken code:
{code}

Fixed code:"""

    response = model.generate_content(prompt)
    return _clean_code(response.text)


def _run_shell_command(command: str, timeout: int = 30) -> ToolResult:
    try:
        result = subprocess.run(
            command,
            shell=True,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
            cwd=str(BASE_DIR)
        )
        output = result.stdout.strip()
        error = result.stderr.strip()
        parts = []
        if output:
            parts.append(f"Output:\n{output}")
        if error:
            parts.append(f"Stderr:\n{error}")
        full_text = "\n\n".join(parts) if parts else f"Command '{command}' executed successfully."

        if result.returncode != 0:
            return ToolResult.fail(
                f"Command '{command}' failed with exit code {result.returncode}.\n{full_text}",
                ErrorCategory.TOOL_EXECUTION_FAILED,
                data={"returncode": result.returncode, "stdout": output, "stderr": error},
            )
        return ToolResult.ok(
            full_text,
            data={"returncode": 0, "stdout": output, "stderr": error},
            verification={"returncode": 0, "verified": True},
        )
    except subprocess.TimeoutExpired:
        return ToolResult.fail(f"Command '{command}' timed out after {timeout}s.", ErrorCategory.TOOL_TIMEOUT)
    except Exception as e:
        cat = classify_error(e)
        return ToolResult.fail(f"Command error: {e}", cat)


def _run_file(path: Path, args: list, timeout: int) -> ToolResult:
    if not path.exists():
        return ToolResult.fail(f"File not found: {path}", ErrorCategory.FILE_NOT_FOUND)

    ext = path.suffix.lower()
    interpreters = {
        ".py":   [sys.executable],
        ".bat":  ["cmd.exe", "/c"],
        ".cmd":  ["cmd.exe", "/c"],
        ".ps1":  ["powershell.exe", "-ExecutionPolicy", "Bypass", "-File"],
        ".js":   ["node"],
        ".ts":   ["ts-node"],
        ".sh":   ["bash"],
        ".rb":   ["ruby"],
        ".php":  ["php"],
        ".exe":  [],
    }
    interp = interpreters.get(ext)
    if interp is None:
        cmd = [str(path)] + (args or [])
    else:
        cmd = interp + [str(path)] + (args or [])

    try:
        result = subprocess.run(
            cmd,
            capture_output=True, text=True,
            encoding="utf-8", errors="replace",
            timeout=timeout, cwd=str(path.parent),
            shell=True if ext in (".bat", ".cmd") else False
        )
        output = result.stdout.strip()
        error  = result.stderr.strip()
        parts  = []
        if output:
            parts.append(f"Output:\n{output}")
        if error:
            parts.append(f"Stderr:\n{error}")
        full_text = "\n\n".join(parts) if parts else f"Executed {path.name} successfully (exit code 0)."

        if result.returncode != 0:
            return ToolResult.fail(
                f"Execution of {path.name} failed with exit code {result.returncode}.\n{full_text}",
                ErrorCategory.TOOL_EXECUTION_FAILED,
                data={"returncode": result.returncode, "stdout": output, "stderr": error},
            )
        return ToolResult.ok(
            full_text,
            data={"returncode": 0, "stdout": output, "stderr": error},
            verification={"returncode": 0, "verified": True},
        )

    except subprocess.TimeoutExpired:
        return ToolResult.fail(f"Execution of {path.name} timed out after {timeout}s.", ErrorCategory.TOOL_TIMEOUT)
    except FileNotFoundError:
        return ToolResult.fail(f"Interpreter or file not found: {cmd[0] if cmd else path}.", ErrorCategory.APP_NOT_FOUND)
    except Exception as e:
        cat = classify_error(e)
        return ToolResult.fail(f"Execution error on {path.name}: {e}", cat)


def _build(description, language, output_path, args, timeout, speak=None, player=None) -> ToolResult:
    if not description:
        return ToolResult.fail("Please describe what you want me to build, sir.", ErrorCategory.COMMAND_UNDERSTOOD_TOOL_UNAVAILABLE)

    if player:
        player.write_log("[Code] Build started...")

    lang = language or "python"

    try:
        code, path = _write(description, lang, output_path, player)
        print(f"[Code] ✅ Written: {path}")
    except Exception as e:
        msg = f"Could not write initial code: {e}"
        if speak:
            speak(msg)
        cat = classify_error(e)
        return ToolResult.fail(msg, cat)

    last_output = ""
    for attempt in range(1, MAX_BUILD_ATTEMPTS + 1):
        print(f"[Code] 🔄 Attempt {attempt}/{MAX_BUILD_ATTEMPTS}")
        if player:
            player.write_log(f"[Code] Attempt {attempt}...")

        run_res = _run_file(path, args, timeout)
        last_output = str(run_res)

        if run_res.success and not _has_error(last_output):
            msg = (
                f"Build complete, sir. "
                f"The code is working after {attempt} attempt{'s' if attempt > 1 else ''}. "
                f"Saved to {path}."
            )
            if speak:
                speak(msg)
            return ToolResult.ok(
                f"{msg}\n\nOutput:\n{last_output}",
                data={"path": str(path), "attempts": attempt},
                artifacts=[str(path)],
                verification={"path": str(path), "verified": True},
            )

        print(f"[Code] ⚠️ Error on attempt {attempt}, fixing...")
        if player:
            player.write_log(f"[Code] Fixing (attempt {attempt})...")

        try:
            code = _fix_code(code, last_output, description)
            _save_file(path, code, f"Auto-fixed generated code for request: {description}")
        except Exception as e:
            msg = f"Could not fix code on attempt {attempt}: {e}"
            if speak:
                speak(msg)
            cat = classify_error(e)
            return ToolResult.fail(msg, cat, artifacts=[str(path)] if path.exists() else [])

    msg = (
        f"I was unable to build a working version after {MAX_BUILD_ATTEMPTS} attempts, sir. "
        f"The last error was: {last_output[:200]}"
    )
    if speak:
        speak(msg)
    return ToolResult.fail(
        f"{msg}\n\nLast code saved to: {path}",
        ErrorCategory.TOOL_EXECUTION_FAILED,
        artifacts=[str(path)] if path.exists() else [],
    )


